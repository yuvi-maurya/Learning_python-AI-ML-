# A variable is a name given to a memory location that stores data.
# In programming, variables are used to hold values that can be changed during the execution of a program.
# They can store different types of data such as integers, strings, floats, and more.


# In Python, you can create a variable by simply assigning a value to a name using the equals sign (=).

# Example of creating variables in Python:

# Integer variable
age = 25

print("Age:", age)  # Output: Age: 25

# String variable
name = "Alice"

print("Name:", name)  # Output: Name: Alice

# Float variable
height = 5.6

print("Height:", height)  # Output: Height: 5.6

# Boolean variable
is_student = True

print("Is Student:", is_student)  # Output: Is Student: True

# List variable
hobbies = ["reading", "swimming", "coding"]

print("Hobbies:", hobbies)  # Output: Hobbies: ['reading', 'swimming', 'coding']


# You can also change the value of a variable by assigning a new value to it.
age = 26
name = "Bob"
height = 6.0
is_student = False
hobbies = ["gaming", "cooking"]

print("Age:", age)  # Output: Age: 26
print("Name:", name)  # Output: Name: Bob
print("Height:", height)  # Output: Height: 6.0
print("Is Student:", is_student)  # Output: Is Student: False
print("Hobbies:", hobbies)  # Output: Hobbies: ['gaming', 'cooking']

