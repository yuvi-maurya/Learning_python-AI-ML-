# Rules for naming variables in Python:
# 1. Variable names can contain letters (a-z, A-Z), digits (0-9), and underscores (_).
# 2. Variable names can not start with a digit.
# 3. Variable names are case-sensitive.
# 4. Variable names can not be Python keywords (e.g., if, else, for, while, etc.).
# 5. It's recommended to use descriptive names that indicate the purpose of the variable.


